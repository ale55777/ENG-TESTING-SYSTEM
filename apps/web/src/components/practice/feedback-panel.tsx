"use client";

import { useEffect, useRef, useState } from "react";
import { Bot, Loader2, RefreshCw, Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { api, errorMessage } from "@/lib/api";
import { useRealtimeEvents } from "@/lib/realtime";
import type { Attempt, Feedback } from "@/lib/types";

/**
 * Shows AI feedback for an attempt. Streams deltas over Ably when available, and always polls the
 * HTTP API until the feedback is final (the HTTP API is the source of truth; realtime is a fast path).
 */
export function useAttemptFeedback(attempt: Attempt | null, onUpdate?: (a: Attempt) => void) {
  const [feedback, setFeedback] = useState<Feedback | null>(attempt?.feedback ?? null);
  const [streamText, setStreamText] = useState("");
  const [pollError, setPollError] = useState<string | null>(null);
  const [nonce, setNonce] = useState(0);
  const onUpdateRef = useRef(onUpdate);
  useEffect(() => {
    onUpdateRef.current = onUpdate;
  });
  const id = attempt?.id;

  useEffect(() => {
    setFeedback(attempt?.feedback ?? null);
    setStreamText("");
  }, [id]); // eslint-disable-line react-hooks/exhaustive-deps

  useRealtimeEvents(
    (e) => {
      if (!id || e.payload?.attempt_id !== id) return;
      if (e.type === "feedback.delta") setStreamText((t) => t + (e.payload.delta || ""));
      if (e.type === "feedback.completed" && e.payload.feedback) setFeedback(e.payload.feedback);
    },
    [id],
  );

  useEffect(() => {
    if (!id || (feedback && feedback.status !== "pending")) return;
    let stop = false;
    let tries = 0;
    const tick = async () => {
      if (stop) return;
      tries++;
      try {
        const r = await api<{ attempt: Attempt }>(`/attempts/${id}`);
        setPollError(null);
        if (r.attempt.feedback && r.attempt.feedback.status !== "pending") {
          setFeedback(r.attempt.feedback);
          onUpdateRef.current?.(r.attempt);
          return;
        }
      } catch (e) {
        setPollError(errorMessage(e));
      }
      if (tries < 45) setTimeout(tick, tries < 5 ? 1500 : 3000);
      else setPollError("Feedback is taking longer than expected. You can retry below.");
    };
    const t = setTimeout(tick, 1500);
    return () => {
      stop = true;
      clearTimeout(t);
    };
  }, [id, feedback, nonce]);

  async function retry() {
    if (!id) return;
    setStreamText("");
    setPollError(null);
    await api(`/attempts/${id}/feedback`, { method: "POST" });
    setFeedback({ status: "pending" });
    setNonce((n) => n + 1);
  }

  return { feedback, streamText, pollError, retry };
}

export function FeedbackPanel({ attempt, onUpdate }: { attempt: Attempt; onUpdate?: (a: Attempt) => void }) {
  const { feedback, streamText, pollError, retry } = useAttemptFeedback(attempt, onUpdate);
  const [retrying, setRetrying] = useState(false);
  const pending = !feedback || feedback.status === "pending";
  const text = pending ? streamText : feedback?.text;

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <Sparkles className="size-5 text-primary" aria-hidden /> Coaching feedback
        </CardTitle>
        <CardDescription>
          {feedback?.source === "ai"
            ? `AI explanation generated by ${feedback.model ?? "Groq GPT-OSS"} from your measured results. Scores above are computed separately and are not changed by the AI.`
            : feedback?.source === "rule-based"
              ? "Rule-based tips derived directly from your measured results."
              : "Explanations are generated after scoring and never change your scores."}
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-3" aria-live="polite" aria-busy={pending}>
        {pending && !streamText && (
          <p className="flex items-center gap-2 text-muted-foreground">
            <Loader2 className="size-4 animate-spin" /> Preparing feedback…
          </p>
        )}
        {text && (
          <div className="flex gap-3">
            <Bot className="mt-0.5 size-5 shrink-0 text-muted-foreground" aria-hidden />
            <p className="whitespace-pre-line leading-relaxed">
              {text}
              {pending && <span className="ml-0.5 animate-pulse">▍</span>}
            </p>
          </div>
        )}
        {feedback?.ai_error && <p className="text-sm text-amber-700 dark:text-amber-400">{feedback.ai_error}</p>}
        {feedback?.status === "unavailable" && <p className="text-sm text-muted-foreground">{feedback.text}</p>}
        {(pollError || feedback?.status === "failed") && (
          <div className="flex flex-wrap items-center gap-2 text-sm">
            <span className="text-destructive">{pollError || feedback?.text}</span>
            <Button
              size="sm"
              variant="outline"
              disabled={retrying}
              onClick={async () => {
                setRetrying(true);
                try {
                  await retry();
                } finally {
                  setRetrying(false);
                }
              }}
            >
              <RefreshCw /> Retry feedback
            </Button>
          </div>
        )}
      </CardContent>
    </Card>
  );
}
